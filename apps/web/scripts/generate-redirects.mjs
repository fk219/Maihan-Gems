/**
 * apps/web/scripts/generate-redirects.mjs
 *
 * Build-time export of the materialised `redirects` table (Phase 4 Task 6).
 *
 * Authority: technical_design/34 section 6-7. The migration stage
 * `cms-redirects` writes one row per source URL into `redirects`. This script
 * reads that table ONCE, at deploy/build time, and rewrites
 * `src/lib/redirects-rows.generated.ts` so the Next proxy can hold the
 * mapping in memory. No per-request database access ever happens.
 *
 * It is NOT run in CI or in unit tests (there is no migrated database there).
 * The storefront's family rules already resolve every URL derivable from the
 * URL text; these rows add the READY_MADE family and any explicit slug change.
 *
 * Usage (against a migrated database; NEVER production):
 *   DATABASE_URL=... pnpm --filter @maihan/web exec node scripts/generate-redirects.mjs
 *
 * The database connection goes through `@maihan/db`'s `createPool` — this app
 * may not import the `pg` driver directly (technical_design/03).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { createPool } from '@maihan/db';

const databaseUrl = process.env['DATABASE_URL'];
if (!databaseUrl || databaseUrl.length === 0) {
  console.error('generate-redirects: DATABASE_URL is required');
  process.exit(1);
}

const pool = createPool(databaseUrl, { statementTimeoutMs: 30_000 });
try {
  const { rows } = await pool.query(
    'SELECT from_path, to_path, status_code FROM redirects ORDER BY from_path',
  );
  const body = rows
    .map(
      (r) =>
        `  { from_path: ${JSON.stringify(r.from_path)}, to_path: ${JSON.stringify(r.to_path)}, status_code: ${Number(r.status_code)} },`,
    )
    .join('\n');
  const header = `/**\n * apps/web/src/lib/redirects-rows.generated.ts\n *\n * GENERATED by apps/web/scripts/generate-redirects.mjs from the migrated\n * \`redirects\` table (technical_design/34 section 6-7). Do not edit by hand.\n *\n * ${rows.length} row(s) exported at ${new Date().toISOString()}.\n */\nimport type { RedirectRow } from './redirects.js';\n\nexport const GENERATED_REDIRECT_ROWS: readonly RedirectRow[] = [\n${body}\n];\n`;
  const here = dirname(fileURLToPath(import.meta.url));
  writeFileSync(join(here, '..', 'src', 'lib', 'redirects-rows.generated.ts'), header, 'utf8');
  console.log(`generate-redirects: wrote ${rows.length} row(s)`);
} finally {
  await pool.end();
}
